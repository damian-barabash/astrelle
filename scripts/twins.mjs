// Regenerates the @container twins at the end of src/styles/global.css.
// The admin's visual editor renders the site inside a frame (container "edt"), where
// @media still measures the browser window — so every `@media (max-width)` block is
// repeated as `@container edt (…)`. Run after touching any responsive block: npm run twins
import { readFileSync, writeFileSync } from 'node:fs'

const FILE = new URL('../src/styles/global.css', import.meta.url)
const MARK = '/* ==== container twins (generated by scripts/twins.mjs — do not edit below) ==== */'

const css = readFileSync(FILE, 'utf8').split(MARK)[0].trimEnd() + '\n'
const twins = []
const re = /@media \((max-width: \d+px)\) \{/g
for (let m; (m = re.exec(css)); ) {
  let depth = 1
  let i = re.lastIndex
  while (depth > 0) {
    if (css[i] === '{') depth++
    else if (css[i] === '}') depth--
    i++
  }
  const body = css
    .slice(re.lastIndex, i - 1)
    // inside the frame the frame itself plays the part of the document
    .replace(/^(\s*)(:root|body)(\s*\{)/gm, '$1.edt__frame$3')
  twins.push(`@container edt (${m[1]}) {${body}}`)
}
writeFileSync(FILE, `${css}\n${MARK}\n${twins.join('\n')}\n`)
console.log(`twins: ${twins.length} blocks`)
